import assert from 'node:assert/strict';
import {mkdirSync} from 'node:fs';
const {chromium}=await import(process.env.PLAYWRIGHT_MODULE||'playwright');
const base=process.env.PRAANI_TEST_URL||'http://localhost:3000';
const output=process.env.PRAANI_TEST_OUTPUT||'test-results';
mkdirSync(output,{recursive:true});
const browser=await chromium.launch({headless:true,channel:'chrome'});
try{
 const page=await browser.newPage({viewport:{width:1440,height:1000}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(base,{waitUntil:'domcontentloaded'});
 assert.equal(await page.locator('#simple-view').isVisible(),true);
 assert.equal(await page.locator('#contribute').isVisible(),false);
 assert.equal(await page.locator('.aotd-card').count(),1);
 assert.equal(await page.locator('#simple-view img').count(),0,'No images in homepage');
 assert.equal(await page.locator('#simple-form').isVisible(),true,'Autocomplete and form visible immediately');
 assert.equal(await page.locator('#simple-extra').isVisible(),false,'Secondary fields progressive');
 assert.ok((await page.locator('#aotd-species').innerText()).length>3);
 assert.ok((await page.locator('#aotd-native').innerText()).length>1);
 assert.ok((await page.locator('#aotd-roman').innerText()).length>2);
 assert.equal(await page.locator('#theme').isVisible(),false);
 const health=await page.request.get(base+'/api/health').then(r=>r.json());
 assert.equal(health.productionConnected,false);
 assert.equal(health.species,2029);
 await page.screenshot({path:output+'/praani-bright-desktop.png',fullPage:true});
 await page.locator('#aotd-add').click();
 assert.equal(await page.locator('#simple-selected').isVisible(),true);
 assert.ok((await page.locator('#simple-search').inputValue()).length>2);
 await page.locator('#simple-search').fill('tiger');
 await page.locator('#simple-results .quick-result').first().waitFor();
 const tigerNames=await page.locator('#simple-results .quick-result strong').allTextContents();
 assert.ok(tigerNames.some(n=>/tiger/i.test(n)));
 assert.ok(tigerNames.length<=8);
 assert.ok(tigerNames.every(n=>!n.includes(String.fromCharCode(92)+'u')));
 await page.locator('#simple-search').press('ArrowDown');
 assert.equal(await page.locator('#simple-results [aria-selected=true]').count(),1);
 await page.locator('#simple-search').press('Enter');
 assert.equal(await page.locator('#simple-selected').isVisible(),true);
 assert.ok((await page.locator('#simple-selected').innerText()).includes('Panthera tigris'));
 await page.locator('#simple-search').fill('Panthera tigris');
 await page.locator('#simple-results .quick-result').first().waitFor();
 await page.locator('#simple-results .quick-result').first().click();
 const unicode='ಪರೀಕ್ಷೆ ಹುಲಿ '+Date.now();
 await page.locator('#simple-name').fill(unicode);
 assert.equal(await page.locator('#simple-extra').isVisible(),true);
 await page.locator('#simple-language').selectOption('Kannada');
 await page.locator('#simple-region').fill('ಪರೀಕ್ಷೆ · Karnataka');
 await page.locator('#simple-source').selectOption('Used in my family or community');
 await page.locator('#simple-context').fill('Automated preview test, not a genuine name. <script>alert(1)</script>');
 await page.locator('#simple-submit').click();
 await page.locator('#simple-success').waitFor({state:'visible',timeout:12000});
 assert.ok((await page.locator('#simple-success-text').innerText()).includes(unicode));
 assert.equal(await page.locator('#simple-success script').count(),0);
 const catalog=JSON.parse(await page.locator('#species-json').textContent());
 const tiger=catalog.find(s=>s.scientific==='Panthera tigris');
 const entry={speciesId:tiger.id,type:tiger.type,localName:unicode,language:'Kannada',region:'ಪರೀಕ್ಷೆ · Karnataka',learnedFrom:'Used in my family or community',context:'test'};
 assert.equal((await page.request.post(base+'/api/contribute',{data:entry,headers:{origin:base}})).status(),409);
 assert.equal((await page.request.post(base+'/api/contribute',{data:entry,headers:{origin:'https://example.org'}})).status(),403);
 assert.equal((await page.request.post(base+'/api/contribute',{data:{...entry,speciesId:'invalid'},headers:{origin:base}})).status(),400);
 await page.locator('#simple-success-next').click();
 assert.equal(await page.locator('#simple-form').isVisible(),true);
 assert.equal(await page.locator('#simple-selected').isVisible(),false);
 await page.locator('#quick-ask').click();
 assert.equal(await page.locator('#quick-ask-panel').isVisible(),true);
 assert.ok((await page.locator('#quick-ask-text').inputValue()).includes('village or family'));
 await page.locator('#view-switch').click();
 assert.equal(await page.locator('#contribute').isVisible(),true);
 assert.equal(await page.locator('#simple-view').isVisible(),false);
 await page.locator('.mission-card').first().waitFor();
 await page.locator('#species-search').fill('tiger');
 await page.locator('#results .result').first().waitFor();
 assert.ok((await page.locator('#results .result strong').allTextContents()).some(n=>/tiger/i.test(n)));
 await page.screenshot({path:output+'/praani-original-archive.png',fullPage:true});
 await page.locator('#view-switch').click();
 for(const width of [320,390,768]){
  await page.setViewportSize({width,height:844});
  await page.goto(base,{waitUntil:'domcontentloaded'});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+2),'Horizontal overflow at '+width);
  assert.equal(await page.locator('.aotd-card').isVisible(),true);
  assert.equal(await page.locator('#simple-search').isVisible(),true);
  if(width===390)await page.screenshot({path:output+'/praani-bright-mobile.png',fullPage:true});
 }
 assert.deepEqual(errors,[]);
 console.log('PRAANI BRIGHT CARD PASS: no images, Animal of the Day, full autocomplete, progressive contribution, Unicode, duplicate/origin validation, archive, mobile 320/390/768.');
}finally{await browser.close()}
