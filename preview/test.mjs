import assert from 'node:assert/strict';
import {mkdirSync} from 'node:fs';
const {chromium}=await import(process.env.PLAYWRIGHT_MODULE||'playwright');
const base=process.env.PRAANI_TEST_URL||'http://localhost:3000';
const output=process.env.PRAANI_TEST_OUTPUT||'test-results';mkdirSync(output,{recursive:true});
const browser=await chromium.launch({headless:true,channel:'chrome'});
try{
 const page=await browser.newPage({viewport:{width:1440,height:950}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(base,{waitUntil:'domcontentloaded'});
 await page.locator('.aotd-card').waitFor({state:'visible'});
 assert.equal(await page.locator('.aotd-card').count(),1);
 assert.equal(await page.locator('.field-note').count(),0);
 assert.equal(await page.locator('#simple-view').count(),0);
 assert.equal(await page.locator('#contribute').isVisible(),true);
 assert.equal(await page.locator('#missions').isVisible(),true);
 assert.equal(await page.locator('#archive').isVisible(),true);
 assert.equal(await page.locator('#species-search').isVisible(),true);
 assert.equal(await page.locator('#local-name').isVisible(),true);
 assert.equal(await page.locator('#language').isVisible(),true);
 const order=await page.evaluate(()=>{const a=document.querySelector('#contribute'),b=document.querySelector('#missions');return Boolean(a.compareDocumentPosition(b)&Node.DOCUMENT_POSITION_FOLLOWING)});
 assert.equal(order,true,'Autocomplete and form should appear before missions');
 assert.equal(await page.locator('.aotd-card img').count(),0);
 const colors=await page.locator('.aotd-card').evaluate(el=>getComputedStyle(el).backgroundColor);
 assert.equal(colors,'rgb(255, 112, 74)','Electric Ember orange card');
 const health=await page.request.get(base+'/api/health').then(r=>r.json());
 assert.equal(health.productionConnected,false);
 assert.equal(health.species,2029);
 await page.locator('#aotd-add').click();
 assert.equal(await page.locator('#selected').isVisible(),true,'Daily card should select species');
 assert.equal(await page.locator('#language').inputValue(),'Kannada');
 await page.screenshot({path:output+'/praani-classic-desktop.png',fullPage:true});
 await page.locator('#species-search').fill('tiger');
 await page.locator('#results .result').first().waitFor();
 const suggestions=await page.locator('#results .result strong').allTextContents();
 assert.ok(suggestions.some(s=>/tiger/i.test(s)));
 assert.ok(suggestions.length<=10);
 assert.ok(suggestions.every(s=>!s.includes(String.fromCharCode(92)+'u')));
 await page.locator('#species-search').press('ArrowDown');
 assert.equal(await page.locator('#results [aria-selected=true]').count(),1);
 await page.locator('#species-search').press('Enter');
 assert.equal(await page.locator('#selected').isVisible(),true);
 await page.locator('#species-search').fill('Panthera tigris');
 await page.locator('#results .result').first().click();
 const name='ಪರೀಕ್ಷೆ ಹುಲಿ '+Date.now();
 await page.locator('#local-name').fill(name);
 await page.locator('#language').selectOption('Kannada');
 await page.locator('#region').fill('ಪರೀಕ್ಷೆ · Karnataka');
 await page.locator('#learned-from').selectOption('Used in my family or community');
 await page.locator('#context').fill('Automated preview test. Not a real name. <script>alert(1)</script>');
 await page.locator('#submit').click();
 await page.locator('#success').waitFor({state:'visible',timeout:10000});
 assert.ok((await page.locator('#success-summary').innerText()).includes(name));
 assert.equal(await page.locator('#cards script').count(),0);
 const species=await page.evaluate(()=>JSON.parse(document.querySelector('#species-json').textContent).find(s=>s.scientific==='Panthera tigris'));
 const entry={speciesId:species.id,type:species.type,localName:name,language:'Kannada',region:'ಪರೀಕ್ಷೆ · Karnataka',learnedFrom:'Used in my family or community',context:'test'};
 assert.equal((await page.request.post(base+'/api/contribute',{data:entry,headers:{origin:base}})).status(),409);
 assert.equal((await page.request.post(base+'/api/contribute',{data:entry,headers:{origin:'https://example.org'}})).status(),403);
 await page.reload({waitUntil:'domcontentloaded'});
 await page.locator('#cards .card').first().waitFor();
 assert.ok((await page.locator('#cards').innerText()).includes(name));
 for(const width of [320,390,768]){
  await page.setViewportSize({width,height:844});
  await page.goto(base,{waitUntil:'domcontentloaded'});
  assert.equal(await page.locator('.aotd-card').isVisible(),true,'Animal card visible on '+width);
  assert.equal(await page.locator('#species-search').isVisible(),true,'Search visible on '+width);
  const overflow=await page.evaluate(()=>document.documentElement.scrollWidth-innerWidth);
  assert.ok(overflow<=2,'Horizontal overflow at '+width+': '+overflow);
  if(width===390)await page.screenshot({path:output+'/praani-classic-mobile.png',fullPage:true});
 }
 assert.deepEqual(errors,[]);
 console.log('PRAANI CLASSIC PASS: original layout, bright animal card, 2029 species, autocomplete, Unicode, submission, duplicate checks, archive, responsive 320/390/768.');
}finally{await browser.close()}
