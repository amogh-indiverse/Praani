import assert from 'node:assert/strict';
import {mkdirSync} from 'node:fs';
const {chromium}=await import(process.env.PLAYWRIGHT_MODULE||'playwright');
const base=process.env.PRAANI_TEST_URL||'http://localhost:3000';
const output=process.env.PRAANI_TEST_OUTPUT||'test-results';
mkdirSync(output,{recursive:true});
const browser=await chromium.launch({headless:true,channel:'chrome'});
try{
 const page=await browser.newPage({viewport:{width:1440,height:950}});
 const errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto(base,{waitUntil:'domcontentloaded'});
 await page.waitForFunction(()=>document.querySelector('#simple-species')?.textContent!=='Finding an animal…');
 assert.equal(await page.locator('#simple-view').isVisible(),true,'Minimal Name Hunt must be homepage');
 assert.equal(await page.locator('#contribute').isVisible(),false,'Original archive stays hidden until requested');
 assert.equal(await page.locator('#simple-form').isVisible(),false,'Form must not be visible before I know a name');
 assert.equal(await page.locator('#simple-know').isVisible(),true);
 assert.equal(await page.locator('#view-switch').innerText(),'Explore archive');
 assert.equal(await page.locator('#theme').isVisible(),false);
 assert.equal(await page.locator('#simple-photo').getAttribute('alt')!==null,true);
 assert.equal(await page.locator('.hunt-play').count(),0,'Old complex hunt removed');
 assert.equal(await page.locator('.fieldbook-screen').count(),0,'Fieldbook dashboard removed');
 const health=await page.request.get(base+'/api/health').then(r=>r.json());
 assert.equal(health.productionConnected,false,'Preview must not connect to production');
 assert.equal(health.species,2029);
 const rights=await page.request.get(base+'/media-rights.json').then(r=>r.json());
 assert.equal(rights.media.length,3);
 for(const m of rights.media){
  assert.equal(m.license,'CC BY 4.0');
  assert.ok(m.creator&&m.source.startsWith('https://commons.wikimedia.org/wiki/File:'));
  assert.ok(m.licenseUrl.startsWith('https://creativecommons.org/licenses/by/4.0/'));
 }
 const hunt=await page.request.get(base+'/api/hunt?language=Kannada').then(r=>r.json());
 assert.equal(hunt.cards.length,3);
 assert.equal(hunt.photographs,3);
 const first=await page.locator('#simple-species').innerText();
 for(let i=0;i<3;i++){
  await page.locator('#simple-photo').waitFor({state:'visible',timeout:20000});
  assert.ok(await page.locator('#simple-photo').evaluate(el=>el.naturalWidth>100),'Species image missing '+i);
  assert.ok((await page.locator('#simple-photo-credit').innerText()).includes('CC BY 4.0'));
  assert.ok((await page.locator('#simple-photo').getAttribute('alt')).includes('photographed by'));
  console.log('RIGHTS CLEARED IMAGE',i,await page.locator('#simple-species').innerText());
  if(i===0)await page.screenshot({path:output+'/praani-simple-desktop.png',fullPage:true});
  await page.locator('#simple-next').click();
 }
 assert.equal(await page.locator('#simple-species').innerText(),first);
 await page.locator('#simple-ask').click();
 assert.equal(await page.locator('#simple-ask-panel').isVisible(),true);
 assert.ok((await page.locator('#simple-ask-text').inputValue()).includes(first));
 await page.locator('#simple-ask-close').click();
 assert.equal(await page.locator('#simple-ask-panel').isVisible(),false);
 await page.locator('#simple-know').click();
 assert.equal(await page.locator('#simple-form').isVisible(),true);
 assert.equal(await page.locator('#simple-step-one').isVisible(),true);
 assert.equal(await page.locator('#simple-step-two').isVisible(),false);
 const name='ಪರೀಕ್ಷೆ ಹೆಸರು '+Date.now();
 await page.locator('#simple-name').fill(name);
 await page.locator('#simple-continue').click();
 assert.equal(await page.locator('#simple-step-two').isVisible(),true);
 assert.equal(await page.locator('#simple-step-one').isVisible(),false);
 assert.ok((await page.locator('#simple-name-review').innerText()).includes(name));
 await page.locator('#simple-language').selectOption('Kannada');
 await page.locator('#simple-region').fill('ಪರೀಕ್ಷೆ · Karnataka');
 await page.locator('#simple-source').selectOption('Used in my family or community');
 await page.locator('#simple-context').fill('Automated preview test, not a real name. <script>alert(1)</script>');
 await page.locator('#simple-submit').click();
 await page.locator('#simple-success').waitFor({state:'visible',timeout:12000});
 assert.ok((await page.locator('#simple-success-text').innerText()).includes(name));
 assert.equal(await page.locator('#simple-success script').count(),0);
 console.log('PROGRESSIVE SUBMISSION PASS',name);
 const entry={speciesId:hunt.cards[0].id,type:hunt.cards[0].type,localName:name,language:'Kannada',region:'ಪರೀಕ್ಷೆ · Karnataka',learnedFrom:'Used in my family or community',context:'Automated test'};
 assert.equal((await page.request.post(base+'/api/contribute',{data:entry,headers:{origin:base}})).status(),409);
 assert.equal((await page.request.post(base+'/api/contribute',{data:entry,headers:{origin:'https://example.org'}})).status(),403);
 assert.equal((await page.request.post(base+'/api/contribute',{data:{...entry,speciesId:'invalid'},headers:{origin:base}})).status(),400);
 await page.locator('#view-switch').click();
 assert.equal(await page.locator('#contribute').isVisible(),true);
 assert.equal(await page.locator('#simple-view').isVisible(),false);
 assert.equal(await page.locator('#view-switch').innerText(),'Back to Name Hunt');
 await page.locator('.mission-card').first().waitFor();
 await page.locator('#species-search').fill('tiger');
 await page.locator('#results .result').first().waitFor();
 const suggestions=await page.locator('#results .result strong').allTextContents();
 assert.ok(suggestions.some(n=>/tiger/i.test(n)));
 assert.ok(suggestions.length<=10);
 assert.ok(suggestions.every(n=>!n.includes(String.fromCharCode(92)+'u')));
 await page.locator('#species-search').press('ArrowDown');
 assert.equal(await page.locator('#results [aria-selected=true]').count(),1);
 await page.locator('#species-search').press('Enter');
 assert.equal(await page.locator('#selected').isVisible(),true);
 await page.locator('#species-search').fill('Panthera tigris');
 await page.locator('#results .result').first().waitFor();
 await page.locator('#results .result').first().click();
 assert.equal(await page.locator('#selected').isVisible(),true);
 await page.screenshot({path:output+'/praani-original-archive.png',fullPage:true});
 await page.locator('#view-switch').click();
 assert.equal(await page.locator('#simple-view').isVisible(),true);
 for(const width of [320,390,768]){
  await page.setViewportSize({width,height:844});
  await page.goto(base,{waitUntil:'domcontentloaded'});
  await page.locator('#simple-photo').waitFor({state:'visible',timeout:20000});
  const overflow=await page.evaluate(()=>document.documentElement.scrollWidth-innerWidth);
  assert.ok(overflow<=2,'Horizontal overflow at '+width+': '+overflow);
  assert.equal(await page.locator('#simple-form').isVisible(),false);
  if(width===390)await page.screenshot({path:output+'/praani-simple-mobile.png',fullPage:true});
  await page.locator('#view-switch').click();
  assert.equal(await page.locator('#contribute').isVisible(),true);
 }
 assert.deepEqual(errors,[]);
 console.log('PRAANI SIMPLE PASS: images, licensing, one-question homepage, progressive form, Unicode, API validation, archive, autocomplete, mobile 320/390/768, no JS errors.');
}finally{await browser.close()}
